'use strict';
const assert=require('assert').strict;
const catalog=require('../service/app-catalog.js'),facts=require('../service/app-facts.js'),apps=require('../service/apps.js');
const d=id=>catalog.describe({appId:id,packageId:id});
assert.equal(d('com.samsung.tv.acr-service-app').role,'tracking');
assert.equal(d('com.samsung.tv.alexa-client').area,'voice');
assert.equal(d('org.tizen.ep-hotel-factory').role,'unused');
assert.equal(d('org.tizen.tv-viewer').role,'keep');
assert.equal(d('com.samsung.tv.csfs').role,'keep');
assert.equal(d('com.samsung.tv.coba.adagent').role,'keep','protected Smart Hub dependency stays keep');
assert.equal(d('org.tizen.provider-resetpsid').area,'samsung','resetting the advertising ID is not tracking');
assert.equal(d('com.samsung.tv.coba.setting.aitech').area,'home');
assert.equal(d('vetrotvapp').role,'keep');
assert.deepEqual(d('com.samsung.tv.aov-service').startsOn,['system event'],'event launches come from the manifest');
assert.ok(d('com.samsung.tv.alexa-client').access.includes('microphone'));
assert.ok(d('com.samsung.tv.alexa-client').referencedBy.length>5);
assert.equal(d('unknown.package.id').source,'name rules');
assert.ok(Object.keys(facts.packages).length>300);
assert.ok(!JSON.stringify(facts).match(/192\.168|\/Users\/|keysequence:\/\//),'no local data or key sequences shipped');
const rows=apps.normalize([{id:'com.samsung.tv.acr-service-app',packageId:'com.samsung.tv.acr-service-app'}],[]);
assert.equal(rows[0].role,'tracking','probe-only rows carry the catalog too');
console.log('PASS app catalog: areas, roles, protected keeps, firmware facts, no private data');
